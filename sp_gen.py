dark,rest=dark.rsplit("}}",1)[0]+"}",dark.rsplit("}}",1)[1]
vars_l,vars_d=[],[]
def conv(block,store,emit_rules):
    out=[]
    for sel,body in re.findall(r'([^{}]+)\{([^{}]*)\}',block):
        sel=sel.strip();decl=[]
        for d in [x for x in body.split(";") if x.strip()]:
            p,v=d.split(":",1);p=p.strip();v=v.strip()
            if re.fullmatch(r'#[0-9A-Fa-f]{3,6}',v):
                for s1 in sel.split(","):
                    n="--sp-"+re.sub(r'[^a-z0-9]+','-',s1.replace(".sp-","").strip())+"-"+p
                    store.append(f"{n}:{v}")
                n="--sp-"+re.sub(r'[^a-z0-9]+','-',sel.split(",")[0].replace(".sp-","").strip())+"-"+p
                decl.append(f"{p}:var({n})" if "," not in sel else None)
                if "," in sel:
                    for s1 in sel.split(","):
                        n1="--sp-"+re.sub(r'[^a-z0-9]+','-',s1.replace(".sp-","").strip())+"-"+p
                        out.append(f".sp-svg {s1.strip()}{{{p}:var({n1})}}")
                    decl.pop()
            else: decl.append(f"{p}:{v}")
        decl=[x for x in decl if x]
        if decl: out.append(",".join(".sp-svg "+s.strip() for s in sel.split(","))+"{"+";".join(decl)+"}")
    return out
L=conv(light,vars_l,True);Dk=conv(dark,vars_d,False)
